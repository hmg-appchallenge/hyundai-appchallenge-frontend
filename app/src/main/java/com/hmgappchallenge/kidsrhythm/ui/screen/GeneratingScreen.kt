/**
 * S05 노래 만드는 중. 서버에 1초마다 진행 상태를 물어 단계를 채우고,
 * 완성되면 mp3를 받아 [AppServices.completedSong]에 넣은 뒤 [onGenerated]로 넘어간다.
 * 뒤로 가면 서버에 만들기를 멈추라고 알린다.
 */
@Composable
fun GeneratingRoute(
    services: AppServices,
    songId: String,
    word: String?,
    onBack: () -> Unit,
    onGenerated: () -> Unit,
    onRetry: () -> Unit,
) {
    var doneCount by remember { mutableIntStateOf(0) }
    var error by remember { mutableStateOf<SongError?>(null) }
    var finished by remember { mutableStateOf(false) }
    val currentOnGenerated by rememberUpdatedState(onGenerated)

    // 만드는 동안 베이스 비트를 계속 튼다 (S03에서 고른 비트 그대로)
    LaunchedEffect(songId) {
        var failures = 0
        while (true) {
            val status = try {
                services.songService.status(songId).also { failures = 0 }
            } catch (e: ServerException) {
                failures++
                if (failures >= MAX_POLL_FAILURES || !e.isNetwork) {
                    error = SongError(e.code, if (e.isNetwork) "노래 서버와 연결이 끊겼어요" else e.message ?: "서버 오류")
                    return@LaunchedEffect
                }
                delay(POLL_MILLIS)
                continue
            }
            doneCount = maxOf(doneCount, GenerationProgress.doneCountForServer(status.step, status.status))
            if (status.status == "FAILED" || status.status == "CANCELED") {
                error = status.error ?: SongError("INTERNAL", "노래를 만들지 못했어요")
                return@LaunchedEffect
            }
            val result = status.result
            if (status.isDone && result != null) {
                val file = services.cacheFileFor(songId)
                try {
                    services.songService.downloadAudio(songId, result, file)
                } catch (e: ServerException) {
                    error = SongError(e.code, "완성된 노래를 받지 못했어요")
                    return@LaunchedEffect
                }
                // 받아 갔으니 서버에 남은 mp3는 지운다 (docs/API.md 6번)
                services.appScope.launch {
                    try { services.songService.deleteSong(songId) } catch (_: ServerException) {}
                }
                services.completedSong = CompletedSong(songId, result, file, System.currentTimeMillis())
                doneCount = GenerationProgress.steps.size
                finished = true
                delay(GenerationProgress.COMPLETE_HOLD_MILLIS)
                currentOnGenerated()
                return@LaunchedEffect
            }
            delay(POLL_MILLIS)
        }
    }
    // 화면을 떠날 때 아직 만드는 중이면 멈춘다
    DisposableEffect(songId) {
        onDispose {
            if (!finished) {
                services.appScope.launch {
                    try { services.songService.deleteSong(songId) } catch (_: ServerException) {}
                }
            }
        }
    }
    // S05-2 뒤로 가기는 바로 나가지 않고 그만둘지 한 번 묻는다
    var confirmQuit by remember { mutableStateOf(false) }
    BackHandler(enabled = error == null && !finished) { confirmQuit = true }
    GeneratingScreen(
        word = word,
        doneCount = doneCount,
        onBack = { if (error == null && !finished) confirmQuit = true else onBack() },
        overlay = {
            if (confirmQuit && error == null) {
                QuitConfirm(onQuit = onBack, onContinue = { confirmQuit = false })
            }
            error?.let { e ->
                MessagePopup(
                    title = "노래를 만들지 못했어요",
                    message = errorText(e),
                    primaryText = "다시 녹음하기",
                    onPrimary = onRetry,
                    secondaryText = "나가기",
                    onSecondary = onBack,
                )
            }
        },
    )
}

/** S05-2 노래 만들기를 그만둘까요? */
@Composable
private fun BoxScope.QuitConfirm(onQuit: () -> Unit, onContinue: () -> Unit) {
    WarmConfirmPopup(
        title = "노래 만들기를 그만둘까요?",
        message = "지금 그만두면 만들던 노래가 사라져요.",
        cancelText = "그만 두기",
        onCancel = onQuit,
        confirmText = "계속 만들기",
        onConfirm = onContinue,
        confirmIcon = R.drawable.ic_check,
        confirmVariant = LargeButtonVariant.Primary,
    )
}

private const val POLL_MILLIS = 1_000L
private const val MAX_POLL_FAILURES = 30

/**
 * 서버가 FAILED로 보내는 다섯 가지 이유. 녹음은 서버가 끝나는 즉시 지워서 같은 녹음으로 다시 만들 수 없고,
 * "다시 녹음하기"로 새로 녹음한다. 외부 AI가 실패하면 서버가 자체 엔진으로 만들어 DONE으로 온다.
 */
private fun errorText(e: SongError): String = when (e.code) {
    "NO_SPEECH" -> "목소리가 들리지 않았어요. 마이크 가까이에서 다시 불러 볼까요?"
    "TOO_SHORT" -> "녹음이 너무 짧아요. 조금 더 길게 불러 주세요."
    "BAD_AUDIO" -> "녹음 소리가 잘 들리지 않았어요. 조용할 때 다시 불러 주세요."
    "TIMEOUT" -> "노래를 만드는 데 시간이 너무 오래 걸렸어요. 다시 녹음해 주세요."
    else -> "노래를 만들지 못했어요. 다시 녹음해 주세요."
}

@Composable
fun GeneratingScreen(word: String?, doneCount: Int, onBack: () -> Unit, overlay: @Composable BoxScope.() -> Unit = {}) {
    SubPage(title = "노래 만드는 중", onBack = onBack, overlay = overlay) {
        Row(modifier = Modifier.fillMaxSize(), horizontalArrangement = Arrangement.spacedBy(StagePanelGap)) {
            Box(
                modifier = Modifier
                    .weight(STAGE_WEIGHT)
                    .fillMaxHeight()
                    .clip(StageShape)
                    .background(AppColors.StageBackground),
            ) {
                StageFloor()
                CharacterCarousel()
                SpeechBubble(
                    text = "조금만 기다려줘!",
                    modifier = Modifier
                        .align(Alignment.TopCenter)
                        .padding(top = 120.dp),
                )
                HintChip(
                    text = "노래를 완성하면 친구가 나와서 춤춰요",
                    modifier = Modifier
                        .align(Alignment.BottomCenter)
                        .padding(bottom = 44.dp),
                )
            }
            Column(
                modifier = Modifier
                    .weight(PANEL_WEIGHT)
                    .fillMaxHeight()
                    // 시안의 내용 상자는 아래에 여백이 조금 더 있다
                    .padding(bottom = 19.dp),
                verticalArrangement = Arrangement.Center,
            ) {
                LoadingSpinner(size = 120.dp, contentDescription = null)
                Text(
                    // 시안은 "보통 5~20초"인데, 에뮬레이터와 서버를 같이 돌리는 노트북에서는 30~65초 걸려서 고쳤다 (docs/API.md 확인 필요 5)
                    text = "보통 1분 정도 걸려요!",
                    style = AppTypography.LabelMedium,
                    color = AppColors.TextDarkTertiary,
                    modifier = Modifier.padding(start = 12.dp, top = 18.dp),
                )
                Text(
                    text = if (word.isNullOrBlank()) "노래를\n만들고 있어요" else "$word 노래를\n만들고 있어요",
                    style = AppTypography.HeadlineLarge,
                    color = AppColors.TextDarkPrimary,
                )
                Column(
                    modifier = Modifier.padding(top = 46.dp),
                    verticalArrangement = Arrangement.spacedBy(25.dp),
                ) {
                    GenerationProgress.steps.forEachIndexed { index, step ->
                        StepRow(label = step.label, state = GenerationProgress.stateOf(index, doneCount))
                    }
                }
            }
        }
    }
}

/**
 * 캐릭터 다섯이 한 줄로 돌아가며 가운데 자리를 바꾼다. 가운데는 선명하고 양옆은 흐리다.
 * 스테이지 양끝은 배경색으로 옅어져 캐릭터가 자연스럽게 들고 난다.
 */
@Composable
private fun BoxScope.CharacterCarousel() {
    val characters = MascotCharacter.entries
    val position = remember { Animatable(characters.indexOf(FirstCenterCharacter).toFloat()) }
    LaunchedEffect(Unit) {
        while (true) {
            delay(CAROUSEL_HOLD_MILLIS)
            position.animateTo(position.value + 1f, tween(CAROUSEL_SLIDE_MILLIS, easing = FastOutSlowInEasing))
        }
    }
    characters.forEachIndexed { index, character ->
        val slot = carouselSlot(index, position.value, characters.size)
        val distance = abs(slot).coerceAtMost(1f)
        Mascot(
            character = character,
            pose = MascotPose.Sitting,
            modifier = Modifier
                .align(Alignment.TopCenter)
                .zIndex(-abs(slot))
                .padding(top = CharacterTop)
                .offset(x = CharacterSpacing * slot)
                .height(CharacterHeight)
                .alpha(1f - (1f - SIDE_CHARACTER_ALPHA) * distance)
                .blur(SideCharacterBlur * distance),
        )
    }
    Box(
        modifier = Modifier
            .fillMaxSize()
            .padding(top = 79.dp)
            .zIndex(1f)
            .background(
                Brush.horizontalGradient(
                    0f to AppColors.StageBackground,
                    0.35f to Color.Transparent,
                    0.71f to Color.Transparent,
                    1f to AppColors.StageBackground,
                ),
            ),
    )
}

/** 가운데(0)에서 몇 칸 떨어졌는지. 한 바퀴를 돌면 반대편 끝으로 넘어간다. */
private fun carouselSlot(index: Int, position: Float, count: Int): Float {
    val half = count / 2f
    return ((index - position) % count + count + half) % count - half
}

@Composable
private fun StepRow(label: String, state: StepState) {
    Row(horizontalArrangement = Arrangement.spacedBy(20.dp), verticalAlignment = Alignment.CenterVertically) {
        StepIndicator(state)
        Text(
            text = label,
            style = AppTypography.BodyLargeStrong,
            color = if (state == StepState.Pending) AppColors.TextDarkQuaternary else AppColors.TextDarkPrimary,
        )
    }
}

@Composable
private fun StepIndicator(state: StepState) {
    val base = Modifier
        .size(StepIndicatorSize)
        .clip(CircleShape)
    when (state) {
        StepState.Done -> Box(base.background(AppColors.BrandOrange), contentAlignment = Alignment.Center) {
            Icon(painterResource(R.drawable.ic_check), contentDescription = "완료", tint = AppColors.BasicStaticLight100, modifier = Modifier.size(28.dp))
        }
        StepState.Active -> Box(
            base
                .background(AppColors.SurfaceBasic)
                .border(4.dp, AppColors.BrandOrange, CircleShape),
            contentAlignment = Alignment.Center,
        ) {
            Box(
                Modifier
                    .size(16.dp)
                    .clip(CircleShape)
                    .background(AppColors.BrandOrange),
            )
        }
        StepState.Pending -> Box(base.background(AppColors.BasicAlphaLight100))
    }
}

