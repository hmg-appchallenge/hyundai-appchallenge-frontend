/** 이웃한 캐릭터의 가운데끼리 거리. */
private val CharacterSpacing = 310.dp

/** 가운데에서 한 칸 이상 떨어진 캐릭터의 흐림 정도와 불투명도. */
private val SideCharacterBlur = 4.dp
private const val SIDE_CHARACTER_ALPHA = 0.4f

/** 캐릭터가 한 자리에 머무는 시간과 왼쪽으로 한 칸 밀리는 시간. 차량 화면이라 시선이 덜 흔들리게 천천히 바꾼다. */
private const val CAROUSEL_HOLD_MILLIS = 3_500L
private const val CAROUSEL_SLIDE_MILLIS = 450

/** 처음 가운데에 서는 캐릭터. */
private val FirstCenterCharacter = MascotCharacter.CAT

private val StepIndicatorSize = 40.dp

/** S05 노래 만드는 중. 노래를 만들고, 단계를 모두 채우면 [onGenerated]로 넘어간다. 뒤로 가면 만들기를 취소한다. */
@Composable
fun GeneratingRoute(
    songGenerator: SongGenerator,
    word: String?,
    onBack: () -> Unit,
    onGenerated: () -> Unit,
) {
    val context = LocalContext.current
    var elapsedMillis by remember { mutableLongStateOf(0L) }
    var generatedAtMillis by remember { mutableStateOf<Long?>(null) }
    val doneCount by remember { derivedStateOf { GenerationProgress.doneCount(elapsedMillis, generatedAtMillis) } }
    val currentOnGenerated by rememberUpdatedState(onGenerated)

    LaunchedEffect(Unit) {
        val start = withFrameMillis { it }
        while (true) {
            withFrameMillis { now -> elapsedMillis = now - start }
        }
    }
    // 화면을 벗어나면 이 효과가 취소되면서 만들기도 함께 취소된다
    LaunchedEffect(Unit) {
        // TODO(오디오): 녹음 파일과 베이스 비트 BPM을 실제 값으로 넘긴다
        // TODO(AI 서버): 받은 노래를 S06으로 넘긴다
        // TODO(디자인): 만들기에 실패했을 때 보여 줄 팝업 시안이 오면 연결한다
        songGenerator.generate(
            SongRequest(recording = File(context.cacheDir, "recording.pcm"), bpm = 80),
        )
        generatedAtMillis = elapsedMillis
    }
    LaunchedEffect(doneCount) {
        if (GenerationProgress.isComplete(doneCount)) {
            delay(GenerationProgress.COMPLETE_HOLD_MILLIS)
            currentOnGenerated()
        }
    }
    // TODO(오디오): 만드는 동안 베이스 비트를 계속 재생한다
    GeneratingScreen(word = word, doneCount = doneCount, onBack = onBack)
}

